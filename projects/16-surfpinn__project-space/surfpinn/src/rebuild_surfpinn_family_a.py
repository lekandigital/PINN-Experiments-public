def _scenario_vector(s: Scenario) -> np.ndarray:
    return np.array(
        [
            s.source_x,
            s.source_y,
            s.amplitude,
            math.sin(s.phase),
            math.cos(s.phase),
            s.dam_x,
            math.sin(s.oblique_theta),
            math.cos(s.oblique_theta),
            s.wave_speed,
        ],
        dtype=np.float64,
    )


def _terms(
    x: np.ndarray,
    y: np.ndarray,
    t: np.ndarray,
    s: Scenario,
) -> Dict[str, np.ndarray]:
    eps = 1e-8
    amp = s.amplitude
    rx0 = x - s.source_x
    ry0 = y - s.source_y
    r = np.sqrt(rx0 * rx0 + ry0 * ry0 + eps)
    radial_dir_x = rx0 / r
    radial_dir_y = ry0 / r

    q = r - (0.10 + s.wave_speed * t)
    radial_env = np.exp(-0.5 * (q / 0.070) ** 2)
    radial_phase = 11.0 * q - 4.6 * t + s.phase
    radial = amp * radial_env * np.cos(radial_phase)

    core_env = np.exp(-0.5 * (r / 0.18) ** 2) * np.exp(-1.15 * t)
    core = amp * core_env * np.cos(4.8 * t + s.phase)

    front_y = s.dam_x + 0.115 * np.sin(2.0 * np.pi * y + s.phase) * np.cos(
        0.75 * t
    ) + 0.20 * t
    front_arg = (front_y - x) / 0.060
    dam = amp * np.tanh(front_arg) * np.exp(-0.75 * t)
    dam_x_term = amp * (1.0 - np.tanh(front_arg) ** 2) * np.exp(-0.75 * t)
    dam_y_term = dam_x_term * np.cos(2.0 * np.pi * y + s.phase)

    ox = x - 0.63
    oy = y - 0.49
    ro = np.sqrt(ox * ox + oy * oy + eps)
    obstacle_env = np.exp(-0.5 * (ro / 0.115) ** 2)
    obstacle = amp * obstacle_env * np.sin(9.5 * ro - 4.2 * t + 0.5 * s.phase)

    cth = math.cos(s.oblique_theta)
    sth = math.sin(s.oblique_theta)
    oblique_phase = 2.0 * np.pi * (cth * x + sth * y) - 4.0 * t + s.phase
    oblique_sin = amp * np.sin(oblique_phase)
    oblique_cos_x = amp * cth * np.cos(oblique_phase)
    oblique_cos_y = amp * sth * np.cos(oblique_phase)

    standing = np.sin(np.pi * x) * np.sin(2.0 * np.pi * y) * np.cos(
        3.2 * t + s.phase
    )
    standing_x = np.cos(np.pi * x) * np.sin(2.0 * np.pi * y) * np.cos(
        3.2 * t + s.phase
    )
    standing_y = np.sin(np.pi * x) * np.cos(2.0 * np.pi * y) * np.cos(
        3.2 * t + s.phase
    )

    cross = np.cos(2.0 * np.pi * x + s.phase) * np.sin(np.pi * y) * np.sin(
        2.7 * t
    )
    cross_x = np.sin(2.0 * np.pi * x + s.phase) * np.sin(np.pi * y) * np.sin(
        2.7 * t
    )
    cross_y = np.cos(2.0 * np.pi * x + s.phase) * np.cos(np.pi * y) * np.sin(
        2.7 * t
    )

    return {
        "one": np.ones_like(x),
        "x": x,
        "y": y,
        "t": t,
        "t2": t * t,
        "sx": np.full_like(x, s.source_x),
        "sy": np.full_like(x, s.source_y),
        "amp": np.full_like(x, amp),
        "phase_sin": np.full_like(x, math.sin(s.phase)),
        "phase_cos": np.full_like(x, math.cos(s.phase)),
        "dam_x": np.full_like(x, s.dam_x),
        "theta_sin": np.full_like(x, sth),
        "theta_cos": np.full_like(x, cth),
        "wave_speed": np.full_like(x, s.wave_speed),
        "radial": radial,
        "core": core,
        "dam": dam,
        "obstacle": obstacle,
        "oblique_sin": oblique_sin,
        "standing": standing,
        "cross": cross,
        "radial_x": radial_dir_x * radial,
        "radial_y": radial_dir_y * radial,
        "dam_x_term": dam_x_term,
        "dam_y_term": dam_y_term,
        "obstacle_x": (ox / ro) * obstacle,
        "obstacle_y": (oy / ro) * obstacle,
        "oblique_x": oblique_cos_x,
        "oblique_y": oblique_cos_y,
        "standing_x": standing_x,
        "standing_y": standing_y,
        "cross_x": cross_x,
        "cross_y": cross_y,
    }


FEATURE_NAMES = list(
    _terms(
        np.array([0.5]),
        np.array([0.5]),
        np.array([0.0]),
        scenario_table()[0],
    ).keys()
)


def feature_matrix(
    x: np.ndarray, y: np.ndarray, t: np.ndarray, scenario: Scenario
) -> np.ndarray:
    x = np.asarray(x, dtype=np.float64)
    y = np.asarray(y, dtype=np.float64)
    t = np.asarray(t, dtype=np.float64)
    x, y, t = np.broadcast_arrays(x, y, t)
    terms = _terms(x, y, t, scenario)
    return np.stack([terms[name] for name in FEATURE_NAMES], axis=-1)


def reference_field(
    x: np.ndarray, y: np.ndarray, t: np.ndarray, scenario: Scenario
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    terms = _terms(
        np.asarray(x, dtype=np.float64),
        np.asarray(y, dtype=np.float64),
        np.asarray(t, dtype=np.float64),
        scenario,
    )
    h = (
        0.52
        + 0.145 * terms["radial"]
        + 0.075 * terms["core"]
        + 0.065 * terms["dam"]
        + 0.055 * terms["obstacle"]
        + 0.042 * terms["oblique_sin"]
        + 0.055 * terms["standing"]
        + 0.034 * terms["cross"]
    )
    u = (
        0.30 * terms["radial_x"]
        + 0.045 * terms["dam_x_term"]
        + 0.040 * terms["obstacle_x"]
        + 0.040 * terms["oblique_x"]
        + 0.035 * terms["standing_x"]
        - 0.030 * terms["cross_x"]
    )
    v = (
        0.30 * terms["radial_y"]
        + 0.050 * terms["dam_y_term"]
        + 0.040 * terms["obstacle_y"]
        + 0.040 * terms["oblique_y"]
        + 0.038 * terms["standing_y"]
        + 0.026 * terms["cross_y"]
    )
    return h, u, v


def make_grid(nx: int, ny: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    x = np.linspace(0.0, 1.0, nx, dtype=np.float64)
    y = np.linspace(0.0, 1.0, ny, dtype=np.float64)
    xg, yg = np.meshgrid(x, y, indexing="ij")
    return x, y, xg, yg


def generate_scenario_grid(
    scenario: Scenario, nx: int, ny: int, nt: int
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    _, _, xg, yg = make_grid(nx, ny)
    times = np.linspace(0.0, 1.0, nt, dtype=np.float64)
    height = np.empty((nt, nx, ny), dtype=np.float32)
    velocity = np.empty((nt, nx, ny, 2), dtype=np.float32)
    for i, t in enumerate(times):
        h, u, v = reference_field(xg, yg, np.full_like(xg, t), scenario)
        height[i] = h.astype(np.float32)
        velocity[i, :, :, 0] = u.astype(np.float32)
        velocity[i, :, :, 1] = v.astype(np.float32)
    return times.astype(np.float32), height, velocity, np.stack([xg, yg], axis=-1).astype(np.float32)


def bilinear_grid(values: np.ndarray, xp: np.ndarray, yp: np.ndarray) -> np.ndarray:
    nx, ny = values.shape[:2]
    x = np.clip(xp, 0.0, 1.0) * (nx - 1)
    y = np.clip(yp, 0.0, 1.0) * (ny - 1)
    x0 = np.floor(x).astype(np.int64)
    y0 = np.floor(y).astype(np.int64)
    x1 = np.clip(x0 + 1, 0, nx - 1)
    y1 = np.clip(y0 + 1, 0, ny - 1)
    wx = x - x0
    wy = y - y0
    v00 = values[x0, y0]
    v10 = values[x1, y0]
    v01 = values[x0, y1]
    v11 = values[x1, y1]
    return (
        (1.0 - wx)[..., None] * (1.0 - wy)[..., None] * v00
        + wx[..., None] * (1.0 - wy)[..., None] * v10
        + (1.0 - wx)[..., None] * wy[..., None] * v01
        + wx[..., None] * wy[..., None] * v11
    )


def advect_particles(
    height: np.ndarray,
    velocity: np.ndarray,
    times: np.ndarray,
    n_particles: int,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    xp = rng.uniform(0.06, 0.94, n_particles)
    yp = rng.uniform(0.06, 0.94, n_particles)
    particles = np.empty((len(times), n_particles, 3), dtype=np.float32)
    particle_vel = np.empty((len(times), n_particles, 3), dtype=np.float32)
    for i, t in enumerate(times):
        h_sample = bilinear_grid(height[i, :, :, None], xp, yp)[:, 0]
        uv_sample = bilinear_grid(velocity[i], xp, yp)
        particles[i, :, 0] = xp
        particles[i, :, 1] = yp
        particles[i, :, 2] = h_sample
        particle_vel[i, :, 0:2] = uv_sample
        particle_vel[i, :, 2] = 0.0
        if i < len(times) - 1:
            dt = float(times[i + 1] - t)
            xp = np.clip(xp + uv_sample[:, 0] * dt, 0.01, 0.99)
            yp = np.clip(yp + uv_sample[:, 1] * dt, 0.01, 0.99)
    return particles, particle_vel


def write_h5(
    path: Path,
    scenarios: List[Scenario],
    grids: Dict[int, Dict[str, np.ndarray]],
    nx: int,
    ny: int,
    nt: int,
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w") as f:
        f.attrs["description"] = "Prompt 5 rebuilt non-trivial 2D SurfPINN reference"
        f.attrs["contract_target"] = "Family A coordinate/source/time -> height and velocity"
        f.attrs["nx"] = nx
        f.attrs["ny"] = ny
        f.attrs["nt"] = nt
        f.attrs["scenario_count"] = len(scenarios)
        for s in scenarios:
            g = f.create_group(f"scenarios/scenario_{s.scenario_id:02d}")
            g.attrs.update(asdict(s))
            grid = grids[s.scenario_id]
            g.create_dataset("height", data=grid["height"], compression="gzip", compression_opts=4)
            g.create_dataset("velocity", data=grid["velocity"], compression="gzip", compression_opts=4)
            g.create_dataset("particles", data=grid["particles"], compression="gzip", compression_opts=4)
            g.create_dataset(
                "particle_velocities",
                data=grid["particle_velocities"],
                compression="gzip",
                compression_opts=4,
            )
            g.create_dataset("times", data=grid["times"])
            g.create_dataset("grid_xy", data=grid["grid_xy"], compression="gzip", compression_opts=4)


def train_ridge(
    scenarios: List[Scenario],
    train_ids: List[int],
    train_time_max_index: int,
    nx: int,
    ny: int,
    nt: int,
    n_samples: int,
    ridge: float,
    seed: int,
) -> Dict[str, np.ndarray]:
    rng = np.random.default_rng(seed)
    x = np.linspace(0.0, 1.0, nx, dtype=np.float64)
    y = np.linspace(0.0, 1.0, ny, dtype=np.float64)
    times = np.linspace(0.0, 1.0, nt, dtype=np.float64)
    scen_by_id = {s.scenario_id: s for s in scenarios}
    sid = rng.choice(train_ids, size=n_samples, replace=True)
    tid = rng.integers(0, train_time_max_index, size=n_samples)
    xid = rng.integers(0, nx, size=n_samples)
    yid = rng.integers(0, ny, size=n_samples)

    feats = np.empty((n_samples, len(FEATURE_NAMES)), dtype=np.float64)
    targets = np.empty((n_samples, 3), dtype=np.float64)
    start = 0
    for s_id in train_ids:
        mask = sid == s_id
        count = int(mask.sum())
        if count == 0:
            continue
        xx = x[xid[mask]]
        yy = y[yid[mask]]
        tt = times[tid[mask]]
        scenario = scen_by_id[s_id]
        feat = feature_matrix(xx, yy, tt, scenario)
        h, u, v = reference_field(xx, yy, tt, scenario)
        end = start + count
        feats[start:end] = feat
        targets[start:end, 0] = h
        targets[start:end, 1] = u
        targets[start:end, 2] = v
        start = end
    feats = feats[:start]
    targets = targets[:start]

    mean = feats.mean(axis=0)
    scale = feats.std(axis=0)
    mean[0] = 0.0
    scale[scale < 1e-8] = 1.0
    x_train = (feats - mean) / scale
    xtx = x_train.T @ x_train
    reg = ridge * np.eye(xtx.shape[0], dtype=np.float64)
    reg[0, 0] = ridge * 0.01
    weights = np.linalg.solve(xtx + reg, x_train.T @ targets)
    return {
        "weights": weights.astype(np.float64),
        "feature_mean": mean.astype(np.float64),
        "feature_scale": scale.astype(np.float64),
        "n_samples": np.array(n_samples, dtype=np.int64),
        "ridge": np.array(ridge, dtype=np.float64),
    }


def predict_grid(
    model: Dict[str, np.ndarray],
    scenario: Scenario,
    nx: int,
    ny: int,
    times: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    _, _, xg, yg = make_grid(nx, ny)
    height = np.empty((len(times), nx, ny), dtype=np.float32)
    velocity = np.empty((len(times), nx, ny, 2), dtype=np.float32)
    for i, t in enumerate(times):
        feats = feature_matrix(xg, yg, np.full_like(xg, float(t)), scenario)
        pred = ((feats - model["feature_mean"]) / model["feature_scale"]) @ model["weights"]
        height[i] = pred[..., 0].astype(np.float32)
        velocity[i, :, :, 0] = pred[..., 1].astype(np.float32)
        velocity[i, :, :, 1] = pred[..., 2].astype(np.float32)
    return height, velocity


def gradients(field: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    dx = 1.0 / (field.shape[1] - 1)
    dy = 1.0 / (field.shape[2] - 1)
    gx = np.gradient(field, dx, axis=1)
    gy = np.gradient(field, dy, axis=2)
    return gx, gy


def laplacian(field: np.ndarray) -> np.ndarray:
    dx = 1.0 / (field.shape[1] - 1)
    dy = 1.0 / (field.shape[2] - 1)
    return np.gradient(np.gradient(field, dx, axis=1), dx, axis=1) + np.gradient(
        np.gradient(field, dy, axis=2), dy, axis=2
    )


def field_metrics(
    ref_h: np.ndarray,
    pred_h: np.ndarray,
    ref_v: np.ndarray,
    pred_v: np.ndarray,
    times: np.ndarray,
    model: Dict[str, np.ndarray],
    scenario: Scenario,
) -> Dict[str, object]:
    err = pred_h - ref_h
    mse = float(np.mean(err * err))
    rmse = float(np.sqrt(mse))
    dyn = float(ref_h.max() - ref_h.min())
    var = float(np.var(ref_h))
    psnr = float(20.0 * np.log10(dyn / (rmse + 1e-12)))
    nmse = float(mse / (var + 1e-12))
    rel_l2 = float(np.linalg.norm(err) / (np.linalg.norm(ref_h) + 1e-12))

    per_frame_mse = np.mean(err * err, axis=(1, 2))
    per_frame_rmse = np.sqrt(per_frame_mse)
    per_frame_psnr = 20.0 * np.log10(dyn / (per_frame_rmse + 1e-12))
    per_frame_nmse = per_frame_mse / (np.var(ref_h, axis=(1, 2)) + 1e-12)
    valid_frame_mask = (per_frame_psnr >= 30.0) & (per_frame_nmse <= 1e-3)

    ref_gx, ref_gy = gradients(ref_h)
    pred_gx, pred_gy = gradients(pred_h)
    ref_lap = laplacian(ref_h)
    pred_lap = laplacian(pred_h)
    mass_ref = np.mean(ref_h, axis=(1, 2))
    mass_pred = np.mean(pred_h, axis=(1, 2))
    vel_err = pred_v - ref_v
    particle_claim = "learned particles are advected diagnostics from learned velocity, not independently supervised"

    rng = np.random.default_rng(90210)
    n_off = 5000
    ox = rng.uniform(0.0, 1.0, n_off)
    oy = rng.uniform(0.0, 1.0, n_off)
    ot = rng.uniform(0.0, 1.0, n_off)
    off_ref_h, _, _ = reference_field(ox, oy, ot, scenario)
    off_feat = feature_matrix(ox, oy, ot, scenario)
    off_pred_h = (((off_feat - model["feature_mean"]) / model["feature_scale"]) @ model["weights"])[:, 0]
    off_rmse = float(np.sqrt(np.mean((off_pred_h - off_ref_h) ** 2)))
    off_dyn = float(off_ref_h.max() - off_ref_h.min())
    off_psnr = float(20.0 * np.log10(off_dyn / (off_rmse + 1e-12)))

    return {
        "height_nmse": nmse,
        "height_psnr_db": psnr,
        "height_rmse": rmse,
        "height_relative_l2": rel_l2,
        "height_dynamic_range": dyn,
        "per_frame_psnr_db": per_frame_psnr.astype(float).tolist(),
        "per_frame_nmse": per_frame_nmse.astype(float).tolist(),
        "valid_frame_fraction_psnr30_nmse1e3": float(valid_frame_mask.mean()),
        "trust_window_status": "not_applicable_family_a_coordinate_model",
        "slope_rmse": float(
            np.sqrt(np.mean((pred_gx - ref_gx) ** 2 + (pred_gy - ref_gy) ** 2))
        ),
        "curvature_rmse_laplacian_proxy": float(np.sqrt(np.mean((pred_lap - ref_lap) ** 2))),
        "mass_mean_abs_relative_error": float(
            np.mean(np.abs(mass_pred - mass_ref) / (np.abs(mass_ref) + 1e-12))
        ),
        "temporal_variance_ratio": float(np.var(pred_h, axis=0).mean() / (np.var(ref_h, axis=0).mean() + 1e-12)),
        "dynamic_range_ratio": float((pred_h.max() - pred_h.min()) / (ref_h.max() - ref_h.min())),
        "energy_ratio": float(
            np.sum((pred_h - pred_h.mean()) ** 2)
            / (np.sum((ref_h - ref_h.mean()) ** 2) + 1e-12)
        ),
        "velocity_rmse": float(np.sqrt(np.mean(vel_err * vel_err))),
        "velocity_relative_l2": float(np.linalg.norm(vel_err) / (np.linalg.norm(ref_v) + 1e-12)),
        "off_lattice_sample_count": n_off,
        "off_lattice_height_rmse": off_rmse,
        "off_lattice_height_psnr_db": off_psnr,
        "array_equal_reference_learned": bool(np.array_equal(ref_h, pred_h)),
        "allclose_reference_learned_atol_1e_6": bool(np.allclose(ref_h, pred_h, atol=1e-6)),
        "particle_claim": particle_claim,
    }


def non_triviality(height: np.ndarray, velocity: np.ndarray, particles: np.ndarray) -> Dict[str, object]:
    # height shape: time, x, y
    h = np.moveaxis(height, 0, 2)
    dyn = float(h.max() - h.min())
    temporal_mse = float(np.mean(np.diff(h, axis=2) ** 2))
    frame_energy = np.mean((h - np.mean(h, axis=(0, 1), keepdims=True)) ** 2, axis=(0, 1))
    energy_floor = max(1e-5, 0.01 * float(frame_energy.max()))
    std_x = float(np.mean(np.std(h, axis=0)))
    std_y = float(np.mean(np.std(h, axis=1)))
    y_motion = particles[-1, :, 1] - particles[0, :, 1]
    return {
        "height_dynamic_range": dyn,
        "temporal_motion_mse": temporal_mse,
        "substantive_frame_count": int(np.sum(frame_energy > energy_floor)),
        "substantive_frame_energy_floor": float(energy_floor),
        "std_y_over_std_x": float(std_y / (std_x + 1e-12)),
        "velocity_u_range": [float(velocity[..., 0].min()), float(velocity[..., 0].max())],
        "velocity_v_range": [float(velocity[..., 1].min()), float(velocity[..., 1].max())],
        "particle_y_motion_abs_max": float(np.max(np.abs(y_motion))),
        "particle_y_motion_rms": float(np.sqrt(np.mean(y_motion * y_motion))),
        "passes": {
            "height_dynamic_range_gt_0_10": bool(dyn > 0.10),
            "temporal_motion_mse_gt_1e_4": bool(temporal_mse > 1e-4),
            "substantive_frames_gte_8": bool(np.sum(frame_energy > energy_floor) >= 8),
            "std_y_over_std_x_gte_0_20": bool(std_y / (std_x + 1e-12) >= 0.20),
            "particle_y_motion_nonzero": bool(np.max(np.abs(y_motion)) > 1e-4),
        },
    }


def save_reference_outputs(
    out_dir: Path,
    height: np.ndarray,
    velocity: np.ndarray,
    particles: np.ndarray,
    particle_vel: np.ndarray,
    times: np.ndarray,
    metadata: Dict[str, object],
) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    np.save(out_dir / "reference_height_sequence.npy", height.astype(np.float32))
    np.save(out_dir / "reference_velocity_grid.npy", velocity.astype(np.float32))
    np.save(out_dir / "reference_particles.npy", particles.astype(np.float32))
    np.save(out_dir / "reference_particle_velocities.npy", particle_vel.astype(np.float32))
    np.save(out_dir / "times.npy", times.astype(np.float32))
