def main() -> None:
    started = time.time()
    timestamp = time.strftime("%Y%m%d_%H%M%S")
    nx = 128
    ny = 128
    nt = 48
    n_particles = 1800
    n_samples = 120_000
    ridge = 5e-4
    train_ids = [0, 1, 2, 3, 4]
    heldout_id = 5
    train_time_max_index = 36
    scenarios = scenario_table()

    log_dir = PROJECT_ROOT / "logs"
    log_dir.mkdir(exist_ok=True)
    log_path = log_dir / f"train_{timestamp}.log"

    def log(msg: str) -> None:
        print(msg)
        with log_path.open("a") as f:
            f.write(msg + "\n")

    log("Prompt 5 SurfPINN rebuild started")
    log(f"framework=NumPy ridge; nx={nx}; ny={ny}; nt={nt}; samples={n_samples}; ridge={ridge}")
    log(f"train_scenarios={train_ids}; heldout_scenario={heldout_id}; train_time_max_index={train_time_max_index}")

    grids: Dict[int, Dict[str, np.ndarray]] = {}
    for scenario in scenarios:
        times, height, velocity, grid_xy = generate_scenario_grid(scenario, nx, ny, nt)
        particles, particle_vel = advect_particles(
            height, velocity, times, n_particles=n_particles, seed=1000 + scenario.scenario_id
        )
        grids[scenario.scenario_id] = {
            "times": times,
            "height": height,
            "velocity": velocity,
            "grid_xy": grid_xy,
            "particles": particles,
            "particle_velocities": particle_vel,
        }
    data_path = PROJECT_ROOT / "data" / "surfpinn_rebuilt_2d_family_a.h5"
    write_h5(data_path, scenarios, grids, nx, ny, nt)
    log(f"wrote_data={data_path}")

    model = train_ridge(
        scenarios,
        train_ids=train_ids,
        train_time_max_index=train_time_max_index,
        nx=nx,
        ny=ny,
        nt=nt,
        n_samples=n_samples,
        ridge=ridge,
        seed=4242,
    )
    heldout = [s for s in scenarios if s.scenario_id == heldout_id][0]
    ref = grids[heldout_id]
