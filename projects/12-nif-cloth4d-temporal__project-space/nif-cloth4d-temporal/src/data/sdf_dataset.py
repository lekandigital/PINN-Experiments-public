"""
HDF5 Dataset loader for cloth SDF sequences.

Loads preprocessed cloth simulation data generated by pyflex_simulator.py
and provides efficient batched access for training.
"""

import h5py
import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
from typing import Optional, Dict, Tuple, List


class ClothSDFDataset(Dataset):
    """
    PyTorch Dataset for cloth SDF sequences.
    
    Loads cloth simulation data from HDF5 format:
    - SDF samples (x, y, z, sdf) for supervision
    - Vertex positions for physics losses
    - Timestamps for temporal indexing
    
    Args:
        data_path: Path to HDF5 dataset
        sequence_length: Number of frames per sample
        stride: Stride between sequence start frames
        num_samples_per_frame: Number of SDF samples to use per frame
        augment: Whether to apply data augmentation
        normalize: Whether to normalize coordinates
    """
    
    def __init__(
        self,
        data_path: str,
        sequence_length: int = 30,
        stride: int = 1,
        num_samples_per_frame: int = 4096,
        augment: bool = False,
        normalize: bool = True,
    ):
        self.data_path = Path(data_path)
        self.sequence_length = sequence_length
        self.stride = stride
        self.num_samples_per_frame = num_samples_per_frame
        self.augment = augment
        self.normalize = normalize
        
        # Load dataset metadata
        with h5py.File(self.data_path, 'r') as f:
            self.num_frames = f.attrs['num_frames']
            self.fps = f.attrs['fps']
            self.cloth_res = f.attrs.get('cloth_res', 32)
            
            # Check what data is available
            self.has_sdf_vol = 'sdf_vol' in f
            self.has_sdf_samples = 'sdf_samples' in f
            self.has_vertices = 'vertices' in f
            
            # Load time array
            self.timestamps = f['time'][:]
            
            # Load faces (shared across frames)
            if 'faces' in f:
                self.faces = torch.tensor(f['faces'][:], dtype=torch.long)
            else:
                self.faces = None
        
        # Compute valid sequence starts
        max_start = self.num_frames - self.sequence_length
        self.sequence_starts = list(range(0, max_start + 1, self.stride))
        
        # Normalization stats (lazy computed)
        self._mean = None
        self._std = None
    
    def __len__(self) -> int:
        """Number of sequences in dataset."""
        return len(self.sequence_starts)
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """
        Get a sequence sample.
        
        Returns:
            Dictionary containing:
                - 'sdf_samples': (seq_len, num_samples, 4) SDF sample points
                - 'positions': (seq_len, num_vertices, 3) vertex positions
                - 'time': (seq_len,) timestamps
                - 'faces': (num_faces, 3) triangle indices
        """
        start_frame = self.sequence_starts[idx]
        end_frame = start_frame + self.sequence_length
        
        sample = {}
        
        with h5py.File(self.data_path, 'r') as f:
            # Load SDF samples if available
            if self.has_sdf_samples:
                sdf_samples = f['sdf_samples'][start_frame:end_frame]  # (seq, N, 4)
                
                # Subsample if needed
                if sdf_samples.shape[1] > self.num_samples_per_frame:
                    indices = np.random.choice(
                        sdf_samples.shape[1],
                        self.num_samples_per_frame,
                        replace=False
                    )
                    sdf_samples = sdf_samples[:, indices, :]
                
                sample['sdf_samples'] = torch.tensor(sdf_samples, dtype=torch.float32)
            
            # Load vertex positions
            if self.has_vertices:
                positions = []
                for t in range(start_frame, end_frame):
                    verts = f[f'vertices/frame_{t}'][:]
                    positions.append(verts)
                positions = np.stack(positions, axis=0)  # (seq, V, 3)
                sample['positions'] = torch.tensor(positions, dtype=torch.float32)
            
            # Load volumetric SDF if available
            if self.has_sdf_vol:
                sdf_vol = f['sdf_vol'][start_frame:end_frame]
                sample['sdf_vol'] = torch.tensor(sdf_vol, dtype=torch.float32)
        
        # Timestamps
        sample['time'] = torch.tensor(
            self.timestamps[start_frame:end_frame],
            dtype=torch.float32
        )
        
        # Faces (same for all frames)
        if self.faces is not None:
            sample['faces'] = self.faces
        
        # Augmentation
        if self.augment:
            sample = self._augment(sample)
        
        # Normalization
        if self.normalize:
            sample = self._normalize(sample)
        
        return sample
    
    def _augment(self, sample: Dict[str, torch.Tensor]) -> Dict[str, torch.Tensor]:
        """Apply data augmentation."""
        # Random rotation around Y axis
        if np.random.rand() > 0.5:
            angle = np.random.uniform(0, 2 * np.pi)
            cos_a, sin_a = np.cos(angle), np.sin(angle)
            rot_matrix = torch.tensor([
                [cos_a, 0, sin_a],
                [0, 1, 0],
                [-sin_a, 0, cos_a]
            ], dtype=torch.float32)
            
            if 'positions' in sample:
                positions = sample['positions']
                sample['positions'] = torch.einsum('ij,...j->...i', rot_matrix, positions)
            
            if 'sdf_samples' in sample:
                sdf = sample['sdf_samples']
                xyz = sdf[..., :3]
                sdf_val = sdf[..., 3:4]
                rotated_xyz = torch.einsum('ij,...j->...i', rot_matrix, xyz)
                sample['sdf_samples'] = torch.cat([rotated_xyz, sdf_val], dim=-1)
        
        # Random flip
        if np.random.rand() > 0.5:
            if 'positions' in sample:
                sample['positions'][..., 0] *= -1
            if 'sdf_samples' in sample:
                sample['sdf_samples'][..., 0] *= -1
        
        return sample
    
    def _normalize(self, sample: Dict[str, torch.Tensor]) -> Dict[str, torch.Tensor]:
        """Normalize spatial coordinates to [-1, 1]."""
        # Use approximate normalization based on expected cloth bounds
        spatial_scale = 2.0  # Cloth is roughly 1m, normalize to [-1, 1]
        
        if 'positions' in sample:
            sample['positions'] = sample['positions'] / spatial_scale
        
        if 'sdf_samples' in sample:
            sample['sdf_samples'][..., :3] = sample['sdf_samples'][..., :3] / spatial_scale
            sample['sdf_samples'][..., 3] = sample['sdf_samples'][..., 3] / spatial_scale
        
        return sample
    
    def get_mesh_topology(self) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """
        Get mesh topology for physics losses.
        
        Returns:
            edges: (num_edges, 2) edge vertex indices
            faces: (num_faces, 3) face vertex indices
            edge_to_faces: (num_interior_edges, 2) adjacent face indices
        """
        if self.faces is None:
            raise ValueError("Faces not available in dataset")
        
        # Build edges from faces
        edges_set = set()
        for face in self.faces.numpy():
            for i in range(3):
                e = tuple(sorted([face[i], face[(i + 1) % 3]]))
                edges_set.add(e)
        
        edges = torch.tensor(list(edges_set), dtype=torch.long)
        
        # Build edge to faces mapping (simplified)
        # For full implementation, need proper mesh connectivity
        edge_to_faces = []
        face_to_edges = {}
        
        for f_idx, face in enumerate(self.faces.numpy()):
            for i in range(3):
                e = tuple(sorted([face[i], face[(i + 1) % 3]]))
                if e not in face_to_edges:
                    face_to_edges[e] = []
                face_to_edges[e].append(f_idx)
        
        for edge, faces_list in face_to_edges.items():
            if len(faces_list) == 2:  # Interior edge
                edge_to_faces.append(faces_list)
        
        edge_to_faces = torch.tensor(edge_to_faces, dtype=torch.long) if edge_to_faces else torch.zeros((0, 2), dtype=torch.long)
        
        return edges, self.faces, edge_to_faces
    
    def get_rest_vertices(self) -> torch.Tensor:
        """Get rest-state vertices (frame 0)."""
        with h5py.File(self.data_path, 'r') as f:
            rest_verts = f['vertices/frame_0'][:]
        return torch.tensor(rest_verts, dtype=torch.float32)


class SyntheticClothDataset(Dataset):
    """
    On-the-fly synthetic cloth dataset for testing.
    
    Generates procedural cloth motion without needing HDF5 files.
    Useful for quick testing and debugging.
    """
    
    def __init__(
        self,
        num_sequences: int = 100,
        sequence_length: int = 30,
        cloth_res: int = 16,
        num_samples_per_frame: int = 1024,
        seed: int = 42,
    ):
        self.num_sequences = num_sequences
        self.sequence_length = sequence_length
        self.cloth_res = cloth_res
        self.num_vertices = cloth_res * cloth_res
        self.num_samples_per_frame = num_samples_per_frame
        
        np.random.seed(seed)
        
        # Pre-generate random sequence parameters
        self.wave_freqs = np.random.uniform(1.0, 4.0, num_sequences)
        self.wave_amps = np.random.uniform(0.05, 0.2, num_sequences)
        self.start_frames = np.random.randint(0, 90, num_sequences)
    
    def __len__(self) -> int:
        return self.num_sequences
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        """Generate a synthetic cloth sequence."""
        wave_freq = self.wave_freqs[idx]
        wave_amp = self.wave_amps[idx]
        start_frame = self.start_frames[idx]
        
        # Rest-state grid
        x = np.linspace(-0.5, 0.5, self.cloth_res)
        z = np.linspace(-0.5, 0.5, self.cloth_res)
        xx, zz = np.meshgrid(x, z)
        rest_x = xx.flatten()
        rest_z = zz.flatten()
        rest_y = np.ones_like(rest_x)
        
        all_positions = []
        all_sdf_samples = []
        timestamps = []
        
        dt = 1.0 / 30.0
        
        for t_idx in range(self.sequence_length):
            t = (start_frame + t_idx) * dt
            timestamps.append(t)
            
            # Procedural animation
            row_idx = np.arange(self.num_vertices) // self.cloth_res
            gravity_factor = row_idx / (self.cloth_res - 1)
            
            wave = wave_amp * np.sin(2 * np.pi * wave_freq * t + rest_x * 5.0)
            wave *= gravity_factor
            
            y_offset = -0.3 * gravity_factor * min(t, 1.0)
            
            curr_x = rest_x + wave * 0.2
            curr_y = rest_y + y_offset + wave * 0.5
            curr_z = rest_z + wave * 0.1
            
            positions = np.stack([curr_x, curr_y, curr_z], axis=1).astype(np.float32)
            all_positions.append(positions)
            
            # Generate SDF samples
            samples = []
            for _ in range(self.num_samples_per_frame):
                v_idx = np.random.randint(self.num_vertices)
                v_pos = positions[v_idx]
                offset = np.random.randn(3).astype(np.float32) * 0.03
                point = v_pos + offset
                
                dists = np.linalg.norm(positions - point, axis=1)
                min_dist = dists.min()
                sign = 1.0 if offset[1] > 0 else -1.0
                
                samples.append(np.concatenate([point, [sign * min_dist]]))
            
            all_sdf_samples.append(np.array(samples, dtype=np.float32))
        
        return {
            'positions': torch.tensor(np.stack(all_positions), dtype=torch.float32),
            'sdf_samples': torch.tensor(np.stack(all_sdf_samples), dtype=torch.float32),
            'time': torch.tensor(timestamps, dtype=torch.float32),
        }


def create_dataloaders(
    data_path: str,
    batch_size: int = 8,
    sequence_length: int = 30,
    num_workers: int = 4,
    train_split: float = 0.8,
    seed: int = 42,
) -> Tuple[DataLoader, DataLoader]:
    """
    Create train and validation dataloaders.
    
    Args:
        data_path: Path to HDF5 dataset
        batch_size: Batch size
        sequence_length: Frames per sequence
        num_workers: DataLoader workers
        train_split: Fraction for training
        seed: Random seed
        
    Returns:
        Tuple of (train_loader, val_loader)
    """
    # Create full dataset
    full_dataset = ClothSDFDataset(
        data_path=data_path,
        sequence_length=sequence_length,
        augment=True,
    )
    
    # Split into train/val
    num_train = int(len(full_dataset) * train_split)
    num_val = len(full_dataset) - num_train
    
    generator = torch.Generator().manual_seed(seed)
    train_dataset, val_dataset = torch.utils.data.random_split(
        full_dataset, [num_train, num_val], generator=generator
    )
    
    # Create loaders
    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=True,
    )
    
    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
    )
    
    return train_loader, val_loader
