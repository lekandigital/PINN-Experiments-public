#!/bin/bash
# configure-keys.sh - Interactive API key configuration for PINN-Experiments

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

PROJECT_ROOT=~/Dev/PINN-Experiments
SECRETS_DIR="$PROJECT_ROOT/.secrets"

echo -e "${BLUE}=============================================="
echo "  PINN-Experiments: API Key Configuration"
echo -e "==============================================${NC}"
echo ""

# Create directories
mkdir -p "$SECRETS_DIR"
chmod 700 "$SECRETS_DIR"

# 1. Vast.ai API Key (required)
echo -e "${YELLOW}[1/4] Vast.ai API Key (REQUIRED)${NC}"
echo "Get your key from: https://cloud.vast.ai/ → Account → API Keys"
echo ""
read -p "Enter your Vast.ai API key: " VAST_KEY

if [[ -z "$VAST_KEY" ]]; then
    echo -e "${RED}Error: Vast.ai API key is required${NC}"
    exit 1
fi

# Save to both locations
echo "$VAST_KEY" > "$SECRETS_DIR/vast_api_key"
echo "$VAST_KEY" > ~/.vast_api_key
chmod 600 "$SECRETS_DIR/vast_api_key"
chmod 600 ~/.vast_api_key
echo -e "${GREEN}✓ Vast.ai key saved${NC}"
echo ""

# 2. HuggingFace Token (optional)
echo -e "${YELLOW}[2/4] HuggingFace Token (optional)${NC}"
echo "Get your token from: https://huggingface.co/settings/tokens"
read -p "Enter HuggingFace token (or press Enter to skip): " HF_KEY

if [[ -n "$HF_KEY" ]]; then
    echo "$HF_KEY" > "$SECRETS_DIR/hf_token"
    chmod 600 "$SECRETS_DIR/hf_token"
    echo -e "${GREEN}✓ HuggingFace token saved${NC}"
else
    echo -e "${BLUE}Skipped${NC}"
fi
echo ""

# 3. Weights & Biases (optional)
echo -e "${YELLOW}[3/4] Weights & Biases API Key (optional)${NC}"
echo "Get your key from: https://wandb.ai/settings"
read -p "Enter W&B API key (or press Enter to skip): " WANDB_KEY

if [[ -n "$WANDB_KEY" ]]; then
    echo "$WANDB_KEY" > "$SECRETS_DIR/wandb_api_key"
    chmod 600 "$SECRETS_DIR/wandb_api_key"
    echo -e "${GREEN}✓ W&B key saved${NC}"
else
    echo -e "${BLUE}Skipped${NC}"
fi
echo ""

# 4. SSH Key for Vast.ai
echo -e "${YELLOW}[4/4] SSH Key Setup${NC}"
SSH_KEY_PATH=~/.ssh/id_ed25519_vastai

if [[ ! -f "$SSH_KEY_PATH" ]]; then
    read -p "No Vast.ai SSH key found. Generate one? [y/N]: " GEN_SSH
    if [[ "$GEN_SSH" =~ ^[Yy]$ ]]; then
        ssh-keygen -t ed25519 -C "vastai-pinn-experiments" -f "$SSH_KEY_PATH" -N ""
        echo -e "${GREEN}✓ SSH key generated at $SSH_KEY_PATH${NC}"
        
        read -p "Attach SSH key to Vast.ai account? [y/N]: " ATTACH_SSH
        if [[ "$ATTACH_SSH" =~ ^[Yy]$ ]]; then
            vastai attach ssh "$(cat ${SSH_KEY_PATH}.pub)"
            echo -e "${GREEN}✓ SSH key attached to Vast.ai${NC}"
        fi
    fi
else
    echo -e "${GREEN}✓ SSH key already exists at $SSH_KEY_PATH${NC}"
fi
echo ""

# Generate .env file
echo -e "${BLUE}Generating .secrets/.env...${NC}"
cat > "$SECRETS_DIR/.env" << EOF
# PINN-Experiments Environment Variables
# Generated by configure-keys.sh on $(date)

VAST_API_KEY=$VAST_KEY
EOF

[[ -n "$HF_KEY" ]] && echo "HF_TOKEN=$HF_KEY" >> "$SECRETS_DIR/.env"
[[ -n "$WANDB_KEY" ]] && echo "WANDB_API_KEY=$WANDB_KEY" >> "$SECRETS_DIR/.env"

chmod 600 "$SECRETS_DIR/.env"
echo -e "${GREEN}✓ .env file created${NC}"
echo ""

# Verify Vast.ai
echo -e "${BLUE}Verifying Vast.ai authentication...${NC}"
if vastai show user > /dev/null 2>&1; then
    echo -e "${GREEN}✓ Vast.ai authentication successful!${NC}"
    vastai show user
else
    echo -e "${RED}✗ Vast.ai authentication failed. Check your API key.${NC}"
    exit 1
fi

echo ""
echo -e "${GREEN}=============================================="
echo "  Configuration Complete!"
echo -e "==============================================${NC}"
echo ""
echo "Keys saved to: $SECRETS_DIR/"
echo ""
echo "Next steps:"
echo "  1. Run: ./vastai-manage.sh list-projects"
echo "  2. Run: ./vastai-manage.sh create <project-name>"
echo ""
